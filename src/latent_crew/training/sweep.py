"""Hyperparameter optimisation as one W&B sweep: all trials are grouped under a single sweep in W&B.

Three commands (scripts/sweep_segmentation.sh wraps the first two):
    python -m latent_crew.training.sweep create configs/sweeps/segmentation.yaml
        registers the sweep in W&B and prints its path (entity/project/sweep_id) as the last line
    python -m latent_crew.training.sweep trial --config configs/sweeps/trial.yaml
        trains one trial; `wandb agent` runs this (the sweep YAML's `command:`), it is not meant to be run by hand
    python -m latent_crew.training.sweep best entity/project/sweep_id
        writes the best trial's values as configs/experiments/sweep_best.yaml, an experiment config on top of the
        100-epoch baseline, for the final full-length run (trials are shorter or stopped early by Hyperband)

A trial passes the trial YAML to `wandb.init`, and W&B deep-merges the sampled values into it (sweep parameters are
nested like the config sections, e.g. training.lr). The merged run config is then validated and trained like any
other config, so W&B shows the full config of every trial. Checkpoints go to <output_dir>/sweeps/<sweep_id>/<run_id>/.
"""

import argparse
from pathlib import Path
from typing import Any, Dict

import wandb
import yaml

from latent_crew.config import SegmentationConfig, read_yaml
from latent_crew.training.train_segmentation import train


def create_sweep(sweep_path: str | Path) -> str:
    """Registers the sweep defined in `sweep_path` and returns its full path for `wandb agent`."""
    with open(sweep_path, "r", encoding="utf-8") as f:
        sweep = yaml.safe_load(f)
    entity, project = sweep.get("entity"), sweep["project"]
    sweep_id = wandb.sweep(sweep, entity=entity, project=project)
    return f"{entity or wandb.Api().default_entity}/{project}/{sweep_id}"


def trial_config(run_config: Dict[str, Any], sweep_id: str, run_id: str) -> SegmentationConfig:
    """Turns the W&B run config (trial YAML + sampled values) into a validated config with its own output dir."""
    raw = {key: value for key, value in run_config.items() if not key.startswith("_")}  # drops W&B's `_wandb`
    experiment = raw["experiment"]
    raw["experiment"] = {**experiment, "name": run_id,
                         "output_dir": str(Path(experiment["output_dir"]) / "sweeps" / sweep_id)}
    return SegmentationConfig.from_dict(raw)


def swept_values(parameters: Dict[str, Any], values: Dict[str, Any]) -> Dict[str, Any]:
    """Picks the swept keys out of a run config, keeping the nesting of the sweep's `parameters:` block."""
    out = {}
    for key, spec in parameters.items():
        if "parameters" in spec:  # nested section, e.g. training: {parameters: {lr: ...}}
            out[key] = swept_values(spec["parameters"], values[key])
        else:
            out[key] = values[key]
    return out


def export_best(sweep_path: str, dest: str | Path, base: str = "../segmentation.yaml") -> Path:
    """Writes the best finished trial of a sweep (by the sweep metric) as an experiment config inheriting `base`.

    Only the swept values are written, so everything else, including the 100 epochs, comes from the baseline.
    """
    sweep = wandb.Api().sweep(sweep_path)
    best = sweep.best_run()
    if best is None:
        raise RuntimeError(f"Sweep {sweep_path} has no finished trial with metric {sweep.config['metric']['name']}")
    metric = sweep.config["metric"]["name"]
    raw = {
        "base": base,
        "experiment": {"name": "sunrgbd_rgbd_resnet50_deeplabv3plus_sweep_best"},
        **swept_values(sweep.config["parameters"], best.config),
        "logging": {"tags": ["sweep_best"]},
    }
    dest = Path(dest)
    dest.parent.mkdir(parents=True, exist_ok=True)
    header = (f"# Experiment: best trial of W&B sweep {sweep_path} (run {best.id}, {metric} "
              f"{best.summary.get(metric)}), generated by `python -m latent_crew.training.sweep best`.\n"
              f"# Only the swept values are listed; the rest, including the full epoch count, comes from the base.\n")
    dest.write_text(header + yaml.dump(raw, default_flow_style=False, sort_keys=False), encoding="utf-8")
    return dest


def run_trial(config_path: str | Path) -> Path:
    """One sweep trial: starts the W&B run with the sampled values, then trains; returns the best checkpoint."""
    base = read_yaml(config_path)
    Path("outputs").mkdir(parents=True, exist_ok=True)
    # Entity, project and sweep id come from the agent's environment
    run = wandb.init(config=base, job_type="segmentation", tags=base["logging"]["tags"], dir="outputs")
    config = trial_config(run.config.as_dict(), run.sweep_id or "no_sweep", run.id)
    run.config.update({"experiment": config.to_dict()["experiment"]}, allow_val_change=True)
    return train(config)  # init_wandb reuses this run instead of starting a new one


def main() -> None:
    """Command-line entry point: `create <sweep.yaml>`, `trial --config <trial.yaml>` or `best <sweep path>`."""
    parser = argparse.ArgumentParser(description="W&B hyperparameter sweep of the segmentation model.")
    commands = parser.add_subparsers(dest="command", required=True)
    create = commands.add_parser("create", help="Register a sweep in W&B and print its path")
    create.add_argument("sweep", help="Sweep definition, e.g. configs/sweeps/segmentation.yaml")
    trial = commands.add_parser("trial", help="Train one trial (run by `wandb agent`)")
    trial.add_argument("--config", required=True, help="Trial base config, e.g. configs/sweeps/trial.yaml")
    best = commands.add_parser("best", help="Write the best trial's values as an experiment config")
    best.add_argument("sweep", help="Sweep path entity/project/sweep_id (printed by `create`)")
    best.add_argument("--out", default="configs/experiments/sweep_best.yaml", help="Where to write the config")
    args = parser.parse_args()

    if args.command == "create":
        print(create_sweep(args.sweep))
    elif args.command == "trial":
        run_trial(args.config)
    else:
        print(f"Wrote {export_best(args.sweep, args.out)}")


if __name__ == "__main__":
    main()
